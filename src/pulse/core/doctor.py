class NetworkingCheck(DoctorCheck):
    def run(self) -> CheckResult:
        offline = get_setting("OFFLINE_MODE", "false").lower() in ("true", "1", "yes")
        details = []
        points = 20
        status = CheckStatus.PASS

        if offline:
            details.append("⚠ OFFLINE_MODE enabled in configuration")
            points -= 5
            status = CheckStatus.WARNING

        try:
            with httpx.Client(timeout=5.0) as client:
                res = client.get("https://api.osv.dev/v1/query")
                if res.status_code < 500:
                    details.append("✓ Remote network connectivity verified (api.osv.dev reachable)")
                else:
                    details.append(f"⚠ Remote network endpoint status: HTTP {res.status_code}")
                    points -= 8
                    status = CheckStatus.WARNING
        except Exception as e:
            if offline:
                details.append(f"○ Offline mode active (Network check skipped: {e})")
            else:
                details.append(f"✖ Network connectivity check failed: {e}")
                points -= 12
                status = CheckStatus.WARNING

        return CheckResult(
            name="Networking Check",
            category="Networking",
            status=status,
            score_points=max(0, points),
            message="Connectivity verified" if status == CheckStatus.PASS else "Connectivity issues detected",
            details=details
        )


