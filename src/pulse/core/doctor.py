class DoctorRunner:
    """Registry runner for executing modular diagnostic checks and computing System Health Score."""

    _checks: List[DoctorCheck] = []

    @classmethod
    def register(cls, check_instance: DoctorCheck) -> None:
        cls._checks.append(check_instance)

    @classmethod
    def initialize_default_checks(cls) -> None:
        cls._checks = [
            ConfigurationCheck(),
            FilesystemCheck(),
            DatabaseCheck(),
            LoggingCheck(),
            NetworkingCheck(),
            ProviderCheck(),
            WebsiteCheck()
        ]

    @classmethod
    def run_all(cls) -> Tuple[int, CheckStatus, List[CheckResult], Dict[str, Tuple[int, int]]]:
        if not cls._checks:
            cls.initialize_default_checks()

        results: List[CheckResult] = []
        cat_scores: Dict[str, Tuple[int, int]] = {}

        total_earned = 0
        total_max = 0

        for check in cls._checks:
            res = check.run()
            results.append(res)

            earned, max_p = cat_scores.get(res.category, (0, 0))
            cat_scores[res.category] = (earned + res.score_points, max_p + res.max_points)

            total_earned += res.score_points
            total_max += res.max_points

        score_pct = int(round((total_earned / total_max) * 100)) if total_max > 0 else 0

        if score_pct >= 85:
            overall_status = CheckStatus.PASS
        elif score_pct >= 70:
            overall_status = CheckStatus.WARNING
        else:
            overall_status = CheckStatus.FAIL

        return score_pct, overall_status, results, cat_scores

    @classmethod
    def export(cls, format: str = "json") -> str:
        score_pct, overall_status, results, cat_scores = cls.run_all()
        data = {
            "system_health_score": f"{score_pct}%",
            "overall_status": overall_status.value,
            "generated_at": datetime.now().isoformat(),
            "tool_version": f"PULSE {__version__}",
            "category_breakdown": {cat: f"{pts[0]}/{pts[1]}" for cat, pts in cat_scores.items()},
            "check_results": [
                {
                    "name": r.name,
                    "category": r.category,
                    "status": r.status.value,
                    "score": f"{r.score_points}/{r.max_points}",
                    "message": r.message,
                    "details": r.details
                }
                for r in results
            ]
        }

        if format.lower() == "json":
            return json.dumps(data, indent=2, ensure_ascii=False)
        elif format.lower() in ("md", "markdown"):
            lines = [
                f"# PULSE Doctor Diagnostic Report",
                f"**Overall System Health Score**: {score_pct}% ({overall_status.value})",
                f"**Tool Version**: PULSE {__version__}",
                "",
                "## Score Breakdown",
                "| Category | Points | Status |",
                "| --- | --- | --- |"
            ]
            for cat, pts in cat_scores.items():
                cat_stat = "PASS" if pts[0] == pts[1] else ("WARNING" if pts[0] >= pts[1] * 0.7 else "FAIL")
                lines.append(f"| {cat} | {pts[0]} / {pts[1]} | {cat_stat} |")
            lines.append("")
            lines.append("## Check Details")
            for r in results:
                lines.append(f"### {r.name} ({r.status.value})")
                lines.append(f"**Score**: {r.score_points}/{r.max_points}")
                for d in r.details:
                    lines.append(f"- {d}")
                lines.append("")
            return "\n".join(lines)

        return json.dumps(data, indent=2)
