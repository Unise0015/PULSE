class CheckStatus(str, Enum):
    PASS = "PASS"
    WARNING = "WARNING"
    FAIL = "FAIL"

@dataclass
class CheckResult:
    name: str
    category: str
    status: CheckStatus
    score_points: int
    max_points: int = 20
    message: str = ""
    details: List[str] = field(default_factory=list)


class DoctorCheck(ABC):
    """Abstract base class for modular system diagnostic checks."""

    @abstractmethod
    def run(self) -> CheckResult:
        pass


class ConfigurationCheck(DoctorCheck):
    def run(self) -> CheckResult:
        from pulse.core.config_service import ConfigService
        cs = ConfigService.get_instance()

        details = []
        points = 20
        status = CheckStatus.PASS

        env_path = get_env_file_path()
        if not env_path.exists():
            details.append("Configuration file '.env' does not exist (using default schema)")
            points -= 5
            status = CheckStatus.WARNING
        else:
            details.append("✓ Configuration file '.env' exists")

        ver = cs.get("CONFIG_SCHEMA_VERSION", 1)
        if ver < 2:
            details.append(f"⚠ Legacy configuration version ({ver}) detected")
            points -= 5
            status = CheckStatus.WARNING
        else:
            details.append(f"✓ Configuration schema version: {ver}")

        gen_by = cs.get("CONFIG_GENERATED_BY", "Unknown")
        details.append(f"✓ Generated by: PULSE {gen_by}")

        diffs = cs.diff_config()
        if diffs:
            details.append(f"✓ Customized settings: {len(diffs)} custom override(s)")

        return CheckResult(
            name="Configuration Check",
            category="Configuration",
            status=status,
            score_points=max(0, points),
            message=f"Configuration schema v{ver} active",
            details=details
        )


class FilesystemCheck(DoctorCheck):
    def run(self) -> CheckResult:
        config_dir = get_config_dir()
        reports_dir = config_dir / "reports"
        cache_dir = config_dir / "cache"

        details = []
        points = 20
        status = CheckStatus.PASS

        if not config_dir.exists():
            details.append(f"✖ Config dir '{config_dir}' missing")
            points -= 10
            status = CheckStatus.FAIL
        else:
            details.append(f"✓ Primary config directory exists: {config_dir}")

        for d_name, d_path in [("Reports", reports_dir), ("Cache", cache_dir)]:
            try:
                d_path.mkdir(parents=True, exist_ok=True)
                test_file = d_path / ".perm_check.tmp"
                with open(test_file, "w") as f:
                    f.write("test")
                test_file.unlink()
                details.append(f"✓ {d_name} directory writable: {d_path}")
            except Exception as e:
                details.append(f"✖ {d_name} directory write failure: {e}")
                points -= 10
                status = CheckStatus.FAIL

        return CheckResult(
            name="Filesystem Check",
            category="Filesystem",
            status=status,
            score_points=max(0, points),
            message="Storage directories validated",
            details=details
        )


class DatabaseCheck(DoctorCheck):
    def run(self) -> CheckResult:
        db_path = get_db_path()
        details = []
        points = 20
        status = CheckStatus.PASS

        if not db_path.exists():
            details.append("⚠ Posture database missing (will auto-create on scan)")
            points -= 5
            status = CheckStatus.WARNING
        else:
            try:
                with sqlite3.connect(db_path) as conn:
                    cursor = conn.cursor()
                    cursor.execute("SELECT count(*) FROM scan_runs")
                    count = cursor.fetchone()[0]
                    details.append(f"✓ Posture history database operational ({count} scan runs recorded)")
            except sqlite3.Error as e:
                details.append(f"✖ Posture database error: {e}")
                points -= 20
                status = CheckStatus.FAIL

        return CheckResult(
            name="Database Check",
            category="Database",
            status=status,
            score_points=max(0, points),
            message="Database health validated",
            details=details
        )


